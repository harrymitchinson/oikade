package registry

import (
	"bufio"
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"slices"
	"strings"
	"unicode"

	"github.com/harrymitchinson/oikade/internal/capability"
)

const (
	registryLine = "//oikade:registry "
	deviceLine   = "//oikade:device "
)

// Render writes the Go file oikade types commits: a value for each device, with its name and a
// framework.Handle for each of its capabilities, so that code naming a device that's gone, or a
// capability it doesn't have, stops compiling. The registry follows as comments, one device to a
// line, which Parse reads back. The same registry always gives the same bytes.
func Render(s Snapshot, pkg string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by oikade types. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)

	names := []Device{}
	for _, d := range s.Devices {
		if !d.Removed {
			names = append(names, d)
		}
	}
	slices.SortFunc(names, func(a, b Device) int { return strings.Compare(a.Name, b.Name) })
	if slices.ContainsFunc(names, func(d Device) bool { return len(handles(d)) > 0 }) {
		b.WriteString("import \"github.com/harrymitchinson/oikade/framework\"\n\n")
	}
	seen := map[string]string{}
	if len(names) > 0 {
		b.WriteString("// The home's devices, from its registry.\n\n")
	}
	for _, d := range names {
		ident := Identifier(d.Name)
		if other, ok := seen[ident]; ok {
			return nil, fmt.Errorf("%s and %s are both %s in Go: rename one", other, d.Name, ident)
		}
		seen[ident] = d.Name
		fmt.Fprintf(&b, "// %s is %s.\nvar %s = struct {\n\tName string\n", ident, describe(d), ident)
		hs := handles(d)
		for _, h := range hs {
			fmt.Fprintf(&b, "\t%s framework.Handle[%s]\n", h.field, h.typ)
		}
		fmt.Fprintf(&b, "}{\n\tName: %q,\n", d.Name)
		for _, h := range hs {
			fmt.Fprintf(&b, "\t%s: framework.Handle[%s]{Device: %q, Capability: framework.%s},\n", h.field, h.typ, d.Name, h.field)
		}
		b.WriteString("}\n\n")
	}

	b.WriteString("// The registry itself, which oikade devices restore reads back.\n\n")
	head, err := json.Marshal(struct {
		Next uint16 `json:"next"`
	}{s.Next})
	if err != nil {
		return nil, err
	}
	fmt.Fprintf(&b, "%s%s\n", registryLine, head)
	ordered := slices.Clone(s.Devices)
	slices.SortFunc(ordered, func(a, b Device) int { return int(a.Endpoint) - int(b.Endpoint) })
	for _, d := range ordered {
		raw, err := json.Marshal(d)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "%s%s\n", deviceLine, raw)
	}
	return format.Source(b.Bytes())
}

// Parse reads back a file Render wrote.
func Parse(file []byte) (Snapshot, error) {
	var s Snapshot
	found := false
	lines := bufio.NewScanner(bytes.NewReader(file))
	lines.Buffer(nil, 1<<20)
	for lines.Scan() {
		line := lines.Text()
		if raw, ok := strings.CutPrefix(line, registryLine); ok {
			if err := json.Unmarshal([]byte(raw), &s); err != nil {
				return Snapshot{}, fmt.Errorf("reading %q: %w", line, err)
			}
			found = true
		}
		if raw, ok := strings.CutPrefix(line, deviceLine); ok {
			var d Device
			if err := json.Unmarshal([]byte(raw), &d); err != nil {
				return Snapshot{}, fmt.Errorf("reading %q: %w", line, err)
			}
			s.Devices = append(s.Devices, d)
		}
	}
	if err := lines.Err(); err != nil {
		return Snapshot{}, err
	}
	if !found {
		return Snapshot{}, errors.New("this isn't a file oikade types wrote")
	}
	return s, nil
}

// Identifier is a device's name in Go: bathroom-fan is BathroomFan.
func Identifier(name string) string {
	var b strings.Builder
	for word := range strings.SplitSeq(name, "-") {
		for i, c := range word {
			if i == 0 {
				c = unicode.ToUpper(c)
			}
			b.WriteRune(c)
		}
	}
	return b.String()
}

// handle is a field of a device's value in Go: one of its capabilities.
type handle struct{ field, typ string }

// handles are a device's capabilities in Go, by name. One the registry of capabilities doesn't know,
// as from a newer plugin, gets none.
func handles(d Device) []handle {
	var out []handle
	for _, name := range d.Capabilities {
		spec, ok := capability.Lookup(name)
		if !ok || slices.ContainsFunc(out, func(h handle) bool { return h.field == spec.Go }) {
			continue
		}
		typ := "bool"
		if spec.Kind == capability.KindNumber {
			typ = "float64"
		}
		out = append(out, handle{field: spec.Go, typ: typ})
	}
	slices.SortFunc(out, func(a, b handle) int { return strings.Compare(a.field, b.field) })
	return out
}

func describe(d Device) string {
	parts := []string{clean(d.Name)}
	if d.Reserved() {
		parts = append(parts, "reserved, and not paired yet")
	}
	if d.Room != "" {
		parts = append(parts, "in "+clean(d.Room))
	}
	if len(d.Capabilities) > 0 {
		parts = append(parts, "with "+clean(strings.Join(d.Capabilities, ", ")))
	}
	return strings.Join(parts, ", ")
}
