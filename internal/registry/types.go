// Render writes the Go file oikade types commits: a value for each device, with its name and a
// oikade.Handle for each of its capabilities, so that code naming a device that's gone, or a
// capability it doesn't have, stops compiling. A device your home declares is under its declared
// name, and the rest under their app's. The same devices always give the same bytes.
func Render(s Snapshot, pkg string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by oikade types. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)

	names := []Device{}
	for _, d := range s.Devices {
		if !d.Removed {
			names = append(names, d)
		}
	}
	slices.SortFunc(names, func(a, b Device) int { return strings.Compare(a.Name, b.Name) })
	if len(names) == 0 {
		b.WriteString("// The host has no devices yet. Pair one, and run oikade types again.\n")
		return format.Source(b.Bytes())
	}
	b.WriteString("import \"github.com/harrymitchinson/oikade\"\n\n")
	b.WriteString("// The home's devices: those it declares under their names, and the rest under their app's.\n\n")
	seen := map[string]string{}
	for _, d := range names {
		ident := Identifier(d.Name)
		if other, ok := seen[ident]; ok {
			return nil, fmt.Errorf("%s and %s are both %s in Go: rename one", other, d.Name, ident)
		}
		seen[ident] = d.Name
		fmt.Fprintf(&b, "// %s is %s.\nvar %s = struct {\n\toikade.Device\n", ident, describe(d), ident)
		hs := handles(d)
		for _, h := range hs {
			fmt.Fprintf(&b, "\t%s oikade.%s\n", h.field, h.typ)
		}
		fmt.Fprintf(&b, "}{\n\tDevice: oikade.Device{Name: %q},\n", d.Name)
		for _, h := range hs {
			fmt.Fprintf(&b, "\t%s: oikade.%s{Device: %q, Capability: oikade.%s},\n", h.field, h.typ, d.Name, h.field)
		}
		b.WriteString("}\n\n")
	}
	return format.Source(b.Bytes())
}

// Handles reads back the devices a file Render wrote has handles for, by name, with their
// capabilities. Rooms and types are your home's declarations'.
func Handles(file []byte) (map[string][]string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), "devices.go", file, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	byGo := map[string]string{}
	for _, name := range capability.Names() {
		if spec, ok := capability.Lookup(name); ok {
			byGo[spec.Go] = name
		}
	}
	out := map[string][]string{}
	for _, decl := range f.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.VAR {
			continue
		}
		for _, spec := range gen.Specs {
			v, ok := spec.(*ast.ValueSpec)
			if !ok || len(v.Values) != 1 {
				continue
			}
			lit, ok := v.Values[0].(*ast.CompositeLit)
			if !ok {
				continue
			}
			name, caps, ok := handlesOf(lit, byGo)
			if ok {
				out[name] = caps
			}
		}
	}
	return out, nil
}

// handlesOf reads one device's value: its Device's name, and a capability for each other field.
func handlesOf(lit *ast.CompositeLit, byGo map[string]string) (string, []string, bool) {
	name, caps := "", []string{}
	for _, e := range lit.Elts {
		kv, ok := e.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		field, ok := kv.Key.(*ast.Ident)
		if !ok {
			continue
		}
		if field.Name == "Device" {
			name = stringField(kv.Value, "Name")
			continue
		}
		if c, ok := byGo[field.Name]; ok {
			caps = append(caps, c)
		}
	}
	slices.Sort(caps)
	return name, caps, name != ""
}

// stringField is a composite literal's string field.
func stringField(e ast.Expr, name string) string {
	lit, ok := e.(*ast.CompositeLit)
	if !ok {
		return ""
	}
	for _, el := range lit.Elts {
		kv, ok := el.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		if k, ok := kv.Key.(*ast.Ident); ok && k.Name == name {
			if v, ok := kv.Value.(*ast.BasicLit); ok && v.Kind == token.STRING {
				s, err := strconv.Unquote(v.Value)
				if err == nil {
					return s
				}
			}
		}
	}
	return ""
}

// Identifier is a device's name in Go: bathroom-fan is BathroomFan.
func Identifier(name string) string {
	var b strings.Builder
	for word := range strings.SplitSeq(name, "-") {
		for i, c := range word {
			if i == 0 {
				c = unicode.ToUpper(c)
			}
			b.WriteRune(c)
		}
	}
	return b.String()
}

// handle is a field of a device's value in Go: one of its capabilities.
type handle struct{ field, typ string }

// handles are a device's capabilities in Go, by name. One the registry of capabilities doesn't know,
// as from a newer plugin, gets none.
func handles(d Device) []handle {
	var out []handle
	for _, name := range d.Capabilities {
		spec, ok := capability.Lookup(name)
		if !ok || slices.ContainsFunc(out, func(h handle) bool { return h.field == spec.Go }) {
			continue
		}
		typ := map[capability.Kind]string{
			capability.KindBool: "Bool", capability.KindNumber: "Number", capability.KindName: "Choice",
		}[spec.Kind]
		out = append(out, handle{field: spec.Go, typ: typ})
	}
	slices.SortFunc(out, func(a, b handle) int { return strings.Compare(a.field, b.field) })
	return out
}

func describe(d Device) string {
	parts := []string{clean(d.Name)}
	if d.Reserved() {
		parts = append(parts, "reserved, and not paired yet")
	}
	if d.Room != "" {
		parts = append(parts, "in "+clean(d.Room))
	}
	if len(d.Capabilities) > 0 {
		parts = append(parts, "with "+clean(strings.Join(d.Capabilities, ", ")))
	}
	return strings.Join(parts, ", ")
}
